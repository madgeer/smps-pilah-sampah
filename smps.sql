    DECLARE v_id_email INT;
    DECLARE v_id_satuan INT;
    DECLARE v_id_laporan INT;

    
    DECLARE v_sampah VARCHAR(100);
    DECLARE i INT DEFAULT 1;
    DECLARE total INT;

    
    SELECT id_email INTO v_id_email
    FROM email
    WHERE nama_email = p_email
    LIMIT 1;

    
    SELECT id_satuan INTO v_id_satuan
    FROM satuan
